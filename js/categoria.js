// ELEMENTOS
const $ = id => document.getElementById(id);

const params = new URLSearchParams(window.location.search);
const categoryName = params.get("cat");

const category = categoryData[categoryName];


// COMPROBAR CATEGORÍA
if (!category) {

    $("categoryPage").innerHTML = `
        <section class="category-error">
            <p class="section-eyebrow">MUTAURA</p>
            <h1>Esta categoría no está disponible.</h1>
            <p>Regresa a Bienestar para descubrir nuestras categorías.</p>
            <a href="bienestar.html" class="hero-button">
                VOLVER A BIENESTAR
            </a>
        </section>
    `;

} else {

    // TÍTULOS Y PRESENTACIÓN
    document.title = `${categoryName} | MUTAURA`;

    $("categoryEyebrow").textContent = category.eyebrow;
    $("categoryTitle").textContent = category.title;
    $("categoryIntro").textContent = category.intro;
    $("categoryImage").src = category.image;
    $("categoryImage").alt = categoryName;

    $("categorySubtitle").textContent = category.subtitle;

    // INFORMACIÓN
    $("categoryWhat").textContent = category.what;
    $("categoryBenefits").textContent = category.benefits;
    $("categoryRoutine").textContent = category.routine;
    $("categoryRecommendations").textContent = category.recommendations;

    // LISTAS
    function renderList(id, items) {
        $(id).innerHTML = items.map(item => `<li>${item}</li>`).join("");
    }

    renderList("categoryTypes", category.types);
    renderList("categoryIngredients", category.ingredients);


 
    // PRODUCTOS
    const products = window.MUTAURA_PRODUCTS || [];

    const categoryProducts = products.filter(product =>
        product.cat === categoryName
    );

    const productGrid = $("categoryProducts");

    $("productsIntro").textContent =
        `Conoce nuestra selección de ${categoryName.toLowerCase()}, creada para acompañar tus momentos de bienestar.`;

    if (categoryProducts.length === 0) {

        productGrid.innerHTML = `
            <p class="category-no-products">
                Próximamente descubrirás nuevos productos en esta categoría.
            </p>
        `;

    } else {

        productGrid.innerHTML = categoryProducts.map(product => `
            <a
                href="producto.html?name=${encodeURIComponent(product.name)}"
                class="category-product-card"
                aria-label="Descubrir ${product.name}"
            >

                <div class="category-product-image">
                    <img
                        src="${product.image}"
                        alt="${product.name}"
                        loading="lazy"
                    >
                </div>

                <div class="category-product-content">

                    <small>${product.cat}</small>

                    <h3>${product.name}</h3>

                    <p>${product.tagline || product.desc}</p>

                    <span class="category-product-link">
                        DESCUBRIR PRODUCTO ↗
                    </span>

                </div>

            </a>
        `).join("");

    }

}
